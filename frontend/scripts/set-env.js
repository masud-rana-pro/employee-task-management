/*
 * Writes src/environments/environment.prod.ts from the API_URL environment variable.
 * Used by "npm run build:prod" (Netlify runs this).
 *
 *   API_URL=https://my-backend.onrender.com/api npm run build:prod
 */
const fs = require('fs');
const path = require('path');

const apiUrl = (process.env.API_URL || '').trim().replace(/\/+$/, '');

if (!apiUrl) {
  console.error('ERROR: the API_URL environment variable is not set.');
  console.error('Example: API_URL=https://my-backend.onrender.com/api');
  process.exit(1);
}
if (!/^https?:\/\//.test(apiUrl)) {
  console.error('ERROR: API_URL must start with http:// or https:// (got "' + apiUrl + '").');
  process.exit(1);
}

const target = path.join(__dirname, '..', 'src', 'environments', 'environment.prod.ts');
const content = `// AUTO-GENERATED by scripts/set-env.js - do not edit by hand.
export const environment = {
  production: true,
  apiUrl: '${apiUrl}'
};
`;

fs.writeFileSync(target, content);
console.log('environment.prod.ts written, apiUrl = ' + apiUrl);
