package com.fifotech.taskmanager.service;

import com.fifotech.taskmanager.entity.Task;
import com.fifotech.taskmanager.enums.TaskStatus;
import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import org.springframework.stereotype.Component;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.time.LocalDateTime;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;

/**
 * Renders the task report with OpenPDF. Pure presentation: it receives already-filtered data,
 * so it knows nothing about roles or the database.
 */
@Component
public class PdfReportGenerator {

    private static final DateTimeFormatter DATE = DateTimeFormatter.ofPattern("dd MMM yyyy");
    private static final DateTimeFormatter DATE_TIME = DateTimeFormatter.ofPattern("dd MMM yyyy HH:mm");

    private static final Font TITLE_FONT = new Font(Font.HELVETICA, 18, Font.BOLD, new Color(33, 37, 41));
    private static final Font META_FONT = new Font(Font.HELVETICA, 10, Font.NORMAL, Color.DARK_GRAY);
    private static final Font HEADER_FONT = new Font(Font.HELVETICA, 9, Font.BOLD, Color.WHITE);
    private static final Font CELL_FONT = new Font(Font.HELVETICA, 9, Font.NORMAL, Color.BLACK);

    /**
     * @param scopeLabel  text such as "All tasks" or "Tasks of your team"
     * @param generatedBy full name of the person who requested the report
     * @param tasks       the tasks to print (assignee / assigner already loaded)
     */
    public byte[] generate(String scopeLabel, String generatedBy, List<Task> tasks) {
        Document document = new Document(PageSize.A4.rotate(), 36, 36, 40, 36);

        try (ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            PdfWriter.getInstance(document, out);
            document.open();

            document.add(new Paragraph("Task Report", TITLE_FONT));
            document.add(new Paragraph("Scope: " + scopeLabel, META_FONT));
            document.add(new Paragraph("Generated by " + generatedBy + " on "
                    + LocalDateTime.now(ZoneOffset.UTC).format(DATE_TIME) + " UTC", META_FONT));
            document.add(new Paragraph(summaryLine(tasks), META_FONT));
            document.add(new Paragraph(" "));

            if (tasks.isEmpty()) {
                document.add(new Paragraph("No tasks found.", META_FONT));
            } else {
                document.add(buildTable(tasks));
            }

            document.close();
            return out.toByteArray();
        } catch (DocumentException | IOException e) {
            throw new IllegalStateException("Could not generate the PDF report", e);
        }
    }

    private String summaryLine(List<Task> tasks) {
        Map<TaskStatus, Integer> counts = new EnumMap<>(TaskStatus.class);
        for (TaskStatus status : TaskStatus.values()) {
            counts.put(status, 0);
        }
        for (Task task : tasks) {
            counts.merge(task.getStatus(), 1, Integer::sum);
        }
        return "Total: " + tasks.size()
                + "   |   Pending: " + counts.get(TaskStatus.PENDING)
                + "   |   In progress: " + counts.get(TaskStatus.IN_PROGRESS)
                + "   |   Done: " + counts.get(TaskStatus.DONE);
    }

    private PdfPTable buildTable(List<Task> tasks) {
        PdfPTable table = new PdfPTable(new float[]{4, 24, 15, 15, 9, 11, 11, 11});
        table.setWidthPercentage(100);
        table.setHeaderRows(1); // header repeats on every page

        for (String header : List.of("#", "Title", "Assigned to", "Assigned by",
                "Priority", "Status", "Deadline", "Created")) {
            PdfPCell cell = new PdfPCell(new Phrase(header, HEADER_FONT));
            cell.setBackgroundColor(new Color(33, 37, 41));
            cell.setPadding(5);
            table.addCell(cell);
        }

        int row = 0;
        for (Task task : tasks) {
            Color background = (row++ % 2 == 0) ? Color.WHITE : new Color(240, 242, 245);
            addCell(table, String.valueOf(row), background);
            addCell(table, task.getTitle(), background);
            addCell(table, task.getAssignedTo().getFullName(), background);
            addCell(table, task.getAssignedBy().getFullName(), background);
            addCell(table, task.getPriority().name(), background);
            addCell(table, task.getStatus().name().replace('_', ' '), background);
            addCell(table, task.getDeadline() != null ? task.getDeadline().format(DATE) : "-", background);
            addCell(table, task.getCreatedAt() != null ? task.getCreatedAt().format(DATE) : "-", background);
        }
        return table;
    }

    private void addCell(PdfPTable table, String text, Color background) {
        PdfPCell cell = new PdfPCell(new Phrase(text == null ? "" : text, CELL_FONT));
        cell.setBackgroundColor(background);
        cell.setPadding(4);
        cell.setVerticalAlignment(Element.ALIGN_MIDDLE);
        table.addCell(cell);
    }
}
